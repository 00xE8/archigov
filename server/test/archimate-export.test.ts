import { test } from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";

// ArchiMate export: deterministic viewpoints derived from the model. The XML must be internally consistent (every
// elementRef/relationshipRef/connection endpoint resolves), readable by our own tolerant parser (round-trip), and
// stable (same model → same geometry). The JSON views feed the Design tab.
process.env.DATA_DIR = fs.mkdtempSync(path.join(os.tmpdir(), "archigov-archimate-"));
delete process.env.AUTH_MODE;
const { db, migrate } = await import("../src/db.js");
await migrate();
const { seedDemo } = await import("../src/seed.js");
seedDemo("test");
const { Hono } = await import("hono");
const { api } = await import("../src/routes.js");
const app = new Hono();
app.route("/", api);
const { buildArchimate, archimateXml } = await import("../src/exporters/archimate.js");
const { parseArchimate } = await import("../src/importers/archimate.js");

const apps = db.prepare("SELECT id, name FROM elements WHERE type='application' AND deleted_at IS NULL").all() as any[];
const call = async (p: string, user = "a.uditor") => app.request(p, { headers: { "x-user": user } });

test("tenant XML is internally consistent and parses back", async () => {
  const r = await call("/exports/archimate");
  assert.equal(r.status, 200);
  assert.match(r.headers.get("content-type") || "", /application\/xml/);
  const xml = await r.text();
  assert.match(xml, /xmlns="http:\/\/www\.opengroup\.org\/xsd\/archimate\/3\.0\/"/);
  // every reference resolves to a declared identifier
  const ids = new Set([...xml.matchAll(/identifier="([^"]+)"/g)].map((m) => m[1]));
  for (const [, ref] of xml.matchAll(/(?:elementRef|relationshipRef)="([^"]+)"/g)) assert.ok(ids.has(ref), `unresolved ref ${ref}`);
  for (const [, ref] of xml.matchAll(/<connection [^>]*(?:source|target)="([^"]+)"/g)) assert.ok(ids.has(ref), `unresolved connection endpoint ${ref}`);
  // our own importer's parser reads it back: same applications, at least every resource as a tech element
  const parsed = parseArchimate(xml);
  const parsedApps = parsed.elements.filter((e) => e.type === "ApplicationComponent").map((e) => e.name).sort();
  for (const a of apps) assert.ok(parsedApps.includes(a.name), `application ${a.name} missing from export`);
  assert.ok(parsed.elements.some((e) => e.type === "Location"), "regions should export as Location elements");
  assert.ok(parsed.relationships.some((r2) => r2.type === "Serving"), "belongs_to should export as Serving");
  // two views per application
  assert.equal((xml.match(/<view /g) || []).length, apps.length * 2);
});

test("single-application export scopes and 404s", async () => {
  const one = await call(`/exports/archimate?application=${apps[0].id}`);
  assert.equal(one.status, 200);
  const xml = await one.text();
  assert.equal((xml.match(/<view /g) || []).length, 2);
  assert.equal((await call("/exports/archimate?application=nope")).status, 404);
});

test("geometry is deterministic", () => {
  const strip = (m: any) => JSON.stringify({ ...m, documentation: "" });
  assert.equal(strip(buildArchimate(null)), strip(buildArchimate(null)));
  const xml = archimateXml(buildArchimate(apps[0].id)).replace(/Generated by archigov on [0-9TZ:.-]+ /, "");
  const xml2 = archimateXml(buildArchimate(apps[0].id)).replace(/Generated by archigov on [0-9TZ:.-]+ /, "");
  assert.equal(xml, xml2);
});

test("JSON views for the Design tab: app node, every resource once, endpoints resolve", async () => {
  for (const a of apps) {
    const r = await call(`/applications/${a.id}/views`);
    assert.equal(r.status, 200);
    const body: any = await r.json();
    assert.equal(body.views.length, 2);
    const [deploy, usage] = body.views;
    assert.equal(deploy.viewpoint, "Implementation and Deployment");
    assert.equal(usage.viewpoint, "Application Usage");
    // the client renders the exchange XML (ArchiMate notation) and selects views by their NCName identifier
    assert.match(body.xml, /^<\?xml/);
    for (const v of body.views) assert.ok(body.xml.includes(`identifier="${v.xml_id}"`), `xml_id ${v.xml_id} resolves in the XML`);
    const resIds = (db.prepare("SELECT from_id f FROM relations WHERE to_id=? AND type='belongs_to' AND deleted_at IS NULL").all(a.id) as any[]).map((x) => x.f);
    for (const view of body.views) {
      const nodeIds = new Set(view.nodes.map((n: any) => n.id));
      assert.ok(nodeIds.has("app"), "application node present");
      for (const c of view.connections) { assert.ok(nodeIds.has(c.source), `source ${c.source}`); assert.ok(nodeIds.has(c.target), `target ${c.target}`); }
      // nodes sit inside the declared canvas
      for (const n of view.nodes) { assert.ok(n.x >= 0 && n.y >= 0 && n.x + n.w <= view.width && n.y + n.h <= view.height, `${view.id} node ${n.id} outside canvas`); }
    }
    for (const rid of resIds) assert.equal(deploy.nodes.filter((n: any) => n.id === `e:${rid}`).length, 1, "resource appears exactly once in the deployment view");
    // every element node except the app itself is inside a container in the deployment view
    for (const n of deploy.nodes) if (n.kind === "element" && n.id !== "app") assert.ok(n.parent, `node ${n.name} has a container`);
  }
  assert.equal((await call("/applications/nope/views")).status, 404);
});

test("connections are routed orthogonally and never pass through an element", async () => {
  for (const a of apps) {
    const body: any = await (await call(`/applications/${a.id}/views`)).json();
    for (const view of body.views) {
      const els = view.nodes.filter((n: any) => n.kind === "element");
      for (const c of view.connections) {
        assert.ok(Array.isArray(c.route) && c.route.length >= 2, `${c.id} carries a route`);
        for (let i = 1; i < c.route.length; i++) {
          const p = c.route[i - 1], q = c.route[i];
          assert.ok(p.x === q.x || p.y === q.y, `${view.id} ${c.id}: segment ${i} is orthogonal`);
          for (const n of els) {
            // own nodes included: anchors touch the border, but no segment enters any body's interior
            const x1 = Math.min(p.x, q.x), x2 = Math.max(p.x, q.x), y1 = Math.min(p.y, q.y), y2 = Math.max(p.y, q.y);
            assert.ok(!(x2 > n.x && x1 < n.x + n.w && y2 > n.y && y1 < n.y + n.h), `${view.id} ${c.id}: segment ${i} crosses ${n.name}`);
          }
        }
      }
      // interior route points travel as exchange-format bendpoints
      for (const c of view.connections) if ((c.route?.length ?? 0) > 2) {
        assert.ok(body.xml.includes(`x="${Math.round(c.route[1].x)}" y="${Math.round(c.route[1].y)}"`), `${c.id}: first bendpoint is in the XML`);
        break;
      }
      // bends are minimised: nothing meanders, and aligned pairs connect straight
      for (const c of view.connections) assert.ok((c.route?.length ?? 2) - 2 <= 6, `${view.id} ${c.id}: at most 6 bends`);
    }
  }
});

test("anchor alignment yields straight routes where endpoints face each other", async () => {
  let straight = 0;
  for (const a of apps) {
    const body: any = await (await call(`/applications/${a.id}/views`)).json();
    for (const view of body.views) for (const c of view.connections) if ((c.route?.length ?? 0) === 2) straight++;
  }
  assert.ok(straight >= 5, `expected a healthy share of bend-free routes across the demo, got ${straight}`);
});
